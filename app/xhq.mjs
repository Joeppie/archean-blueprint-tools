import { chromium } from '@playwright/test';
const b = await chromium.launch({ headless: true, args: ['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=vulkan'], env: { ...process.env, VK_ICD_FILENAMES: '/usr/share/vulkan/icd.d/radeon_icd.json' } });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.addInitScript(() => { localStorage.setItem('archean-app-debug', '1'); localStorage.setItem('archean-app-backdrop', 'none'); localStorage.setItem('archean-worldsim', ''); });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5294/?craft=3381670618', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => /SCENE PASS/.test(document.title), null, { timeout: 150000 });
await p.getByTestId('xenon-menu').click();
await p.locator('[data-testid^="xenon-comp-"]').first().click();
await p.getByTestId('xenon-on').waitFor({ timeout: 60000 });
// worldsim: pin altitude base 2000 + $val + 2 BEFORE the edit (like the leg)
await p.getByTestId('xenon-side-world').click();
const alt = p.getByTestId('worldsim-row-navinstrument.altitude_meters_from_sea_level');
await alt.waitFor({ timeout: 15000 });
await p.getByTestId('worldsim-base-navinstrument.altitude_meters_from_sea_level').fill('2000');
await p.getByTestId('worldsim-ov-navinstrument.altitude_meters_from_sea_level').fill('$val + 2');
await p.waitForTimeout(1500);
await p.getByTestId('xenon-edit').click();
const body1 = p.locator('.cm-line', { hasText: 'return $corr' }).first();
await body1.click();
await p.keyboard.press('Home');
await p.keyboard.type('\tprint(text("alt: {}", input_number(4, 2)))');
await p.keyboard.press('Enter');
await p.getByTestId('xenon-save').click();
await p.getByTestId('xenon-on').waitFor({ timeout: 90000 });
await p.getByTestId('xenon-side-console').click();
await p.waitForTimeout(4000);
console.log('console:', JSON.stringify((await p.getByTestId('xenon-log').innerText()).split('\n').filter(l => l.includes('alt:')).slice(-3)));
await b.close();
