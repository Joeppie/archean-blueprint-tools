import { chromium } from '@playwright/test';
const b = await chromium.launch({ headless: true, args: ['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=vulkan'], env: { ...process.env, VK_ICD_FILENAMES: '/usr/share/vulkan/icd.d/radeon_icd.json' } });
const ctx = await b.newContext({ viewport: { width: 1500, height: 900 } });
await ctx.addInitScript(() => { localStorage.setItem('archean-app-debug', '1'); localStorage.setItem('archean-app-backdrop', 'none'); localStorage.setItem('archean-worldsim', ''); });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String(e).slice(0, 300)));
p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text().slice(0, 300)); });
await p.goto('http://127.0.0.1:5294/?craft=3294880085', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => /SCENE PASS/.test(document.title), null, { timeout: 150000 });
await p.getByTestId('xenon-menu').click();
await p.locator('[data-testid^="xenon-comp-"]').first().click();
await p.getByTestId('xenon-on').waitFor({ timeout: 60000 });
await p.waitForTimeout(1200);
const varTok = p.locator('.cm-content span').filter({ hasText: /^\$\S+$/ }).first();
console.log('varTok visible:', await varTok.isVisible());
await varTok.click({ button: 'right' });
console.log('menu:', await p.getByTestId('xc-ctxmenu').isVisible());
await p.getByTestId('ctx-breakpoint').click();
await p.waitForTimeout(400);
console.log('bp markers:', await p.locator('.xc-bp').count());
await varTok.click({ button: 'right' });
await p.getByTestId('ctx-breakpoint').click();
await p.waitForTimeout(400);
console.log('after remove bp markers:', await p.locator('.xc-bp').count());
console.log('dialog present:', await p.getByTestId('xenon-dialog').count(), 'tabs:', await p.locator('[data-testid^="xenon-tab-"]').count());
console.log('errors:', errs.slice(0, 3).join(' || ') || 'none');
await b.close();
